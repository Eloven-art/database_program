def apply(path, reps):
    txt = io.open(path, encoding="utf-8").read()
    done = 0
    for old, new in reps:
        n = txt.count(old)
        if n == 0:
            # 已替换过（幂等跳过）
            continue
        assert n == 1, "「%s」在 %s 中出现 %d 次（期望 1 次）" % (old[:40], path, n)
        txt = txt.replace(old, new)
        done += 1
    io.open(path, "w", encoding="utf-8").write(txt)
    print("OK %s：%d 处替换" % (path, done))


